"""Extract exact original SEC statement facts; no portfolio computation."""
import hashlib,json,re
from pathlib import Path
from html.parser import HTMLParser
ROOT=Path(__file__).resolve().parents[4]
AREA=ROOT/'data/us_restoration'
HERE=Path(__file__).resolve().parent
DOCS=ROOT.parent/'us_source_reports/tsm_gev'
FLOWS=('operating_income','net_income','operating_cash_flow')
class Text(HTMLParser):
    def __init__(self):super().__init__();self.parts=[]
    def handle_data(self,d):self.parts.append(d)
def flat(path):
    p=Text();p.feed(path.read_text());return re.sub(r'\s+',' ',' '.join(p.parts))
def save(name,obj): (HERE/name).write_text(json.dumps(obj,indent=2)+'\n')
def base(t,period,date,url,currency):
    return dict(ticker=t,period_end=period,publication_date=date,availability_date=date,currency=currency,unit='million',income_source=url,balance_source=url,cashflow_source=url,date_source=url,notes=[])
def prior(a):return dict(**{k:a[k] for k in FLOWS},period_end=a['period_end'],publication_date=a['publication_date'],availability_date=a['availability_date'],source=a['income_source'])
annual=[];interim=[];evidence=[];manifest=[]
# Original reviewed or audited consolidated statements included as 6-K exhibits.
files=[]
for path in sorted(DOCS.glob('TSM_202*-*.txt')):
    date=path.name[4:14]
    if date=='2026-04-16':continue
    s=flat(path)
    if 'CONSOLIDATED BALANCE SHEETS' not in s:continue
    s=s[s.index('CONSOLIDATED BALANCE SHEETS'):]
    accession=re.search(r'ACCESSION NUMBER:\s*(\d{10}-\d{2}-\d{6})',path.read_text()).group(1)
    url=f'https://www.sec.gov/Archives/edgar/data/1046179/{accession.replace("-","")}/{accession}.txt'
    year=int(date[:4]);month=int(date[5:7]);q={2:4,5:1,8:2,11:3}[month];year-=month==2
    period=f'{year}-'+{1:'03-31',2:'06-30',3:'09-30',4:'12-31'}[q]
    labels=[('total_assets','TOTAL','LIABILITIES AND EQUITY'),('current_liabilities','Total current liabilities','NONCURRENT LIABILITIES'),('operating_income','INCOME FROM OPERATIONS','NON-OPERATING INCOME'),('net_income','NET INCOME','OTHER COMPREHENSIVE'),('operating_cash_flow','Net cash generated by operating activities',None)]
    vals={}; snippets={}
    for field,start,end in labels:
        a=s.index(start);b=s.index(end,a) if end else a+110
        fragment=s[a:b]; nums=re.findall(r'\d{1,3}(?:,\d{3})+',fragment)
        count=2 if field=='operating_cash_flow' or q in (1,4) else (3 if field in ('total_assets','current_liabilities') else 4)
        assert len(nums)>=count,(path,field,nums)
        vals[field]=[int(x.replace(',',''))/1000 for x in nums[:count]]
        snippets[field]=fragment
    row=base('TSM',period,date,url,'TWD')
    row.update(total_assets=vals['total_assets'][0],current_liabilities=vals['current_liabilities'][0])
    row['notes']=['Exact original statement values in TWD thousands divided by 1,000. Net income includes noncontrolling interests. Availability uses complete financial statement 6-K filing date, conservatively later than earnings announcement.', 'Annual and interim comparisons reconciled to originals; no selected flow-basis restatements identified.', 'All TSM inputs use Taiwan-IFRSs (IFRS endorsed by Taiwan FSC), consistently across annual and interim 6-K statements. IASB-IFRS 20-F figures differ and are not mixed into this panel; see accounting_basis_evidence.json.']
    if q==4:row.update({f:vals[f][0] for f in FLOWS});annual.append(row)
    else:
        idx=0 if q==1 else 2
        row.update(fiscal_year=year,fiscal_quarter=q,ytd={f:vals[f][0 if f=='operating_cash_flow' else idx] for f in FLOWS},prior_ytd={f:vals[f][1 if f=='operating_cash_flow' else idx+1] for f in FLOWS},ttm_compatible=True)
        interim.append(row)
    evidence.append(dict(ticker='TSM',period_end=period,filed=date,accession=accession,source=url,statement_unit='TWD thousand',selected_row_amounts_TWD_million=vals,factual_excerpts=snippets))
    manifest.append(dict(file=path.name,url=url,sha256=hashlib.sha256(path.read_bytes()).hexdigest()))
for row in interim:
    a=next(a for a in annual if a['ticker']==row['ticker'] and a['period_end']==f"{row['fiscal_year']-1}-12-31")
    row['prior_annual']=prior(a)
    assert a['availability_date']<row['publication_date']
# GE Vernova: actual combined FY2022/FY2023 statements from pre-spin registration.
reg=DOCS/'GEV_registration_exhibit.html';s=flat(reg)
url='https://www.sec.gov/Archives/edgar/data/1996810/000119312524059354/d542465dex991.htm'
for year,v in [(2022,[-2881,-2722,-114,44471,26042]),(2023,[-923,-474,1186,46121,29306])]:
    row=base('GEV',f'{year}-12-31','2024-03-05',url,'USD')
    row.update(dict(zip((*FLOWS,'total_assets','current_liabilities'),v)))
    row['notes']=['Actual combined financial statements, not pro forma, in March 5, 2024 public Form 10 amendment exhibit 99.1, pages F-4/F-6/F-7. Historical financial coverage does not permit trading before April 2, 2024 listing.']
    annual.append(row)
for name in ['COMBINED STATEMENT OF INCOME','COMBINED STATEMENT OF FINANCIAL POSITION','COMBINED STATEMENT OF CASH FLOWS']:
    i=s.rfind(name);assert i>=0
    evidence.append(dict(ticker='GEV',source=url,filed='2024-03-05',statement=name,factual_excerpt=s[i:i+3800]))
manifest.append(dict(file=reg.name,url=url,sha256=hashlib.sha256(reg.read_bytes()).hexdigest()))
facts=json.loads((DOCS/'GEV_companyfacts.json').read_text())['facts']['us-gaap']
subs=json.loads((DOCS/'GEV_submissions.json').read_text())['filings']['recent']
primary={a:subs['primaryDocument'][i] for i,a in enumerate(subs['accessionNumber'])}
tags=dict(operating_income='OperatingIncomeLoss',net_income='ProfitLoss',operating_cash_flow='NetCashProvidedByUsedInOperatingActivities',total_assets='Assets',current_liabilities='LiabilitiesCurrent')
def fact(field,end,start=None,accn=None):
    rs=[r for r in facts[tags[field]]['units']['USD'] if r['end']==end and r.get('start')==start and r['filed']<'2026-10-01' and (not accn or r['accn']==accn)]
    assert rs,(field,end,start,accn)
    r=sorted(rs,key=lambda r:(r['filed'],r['accn']))[0]
    if accn:assert len({r['val'] for r in rs})==1
    evidence.append(dict(ticker='GEV',concept='us-gaap:'+tags[field],unit='USD',**r))
    return r
for year,q in [(2024,4),(2025,4)]+[(y,q) for y in range(2024,2027) for q in (1,2,3) if (y,q)<(2026,3)]:
    period=f'{year}-'+{1:'03-31',2:'06-30',3:'09-30',4:'12-31'}[q]
    r=fact('operating_income',period,f'{year}-01-01');a=r['accn'];date=r['filed']
    url=f'https://www.sec.gov/Archives/edgar/data/1996810/{a.replace("-","")}/{primary[a]}'
    row=base('GEV',period,date,url,'USD')
    row.update({f:fact(f,period,accn=a)['val']/1e6 for f in ('total_assets','current_liabilities')})
    v={f:fact(f,period,f'{year}-01-01',a)['val']/1e6 for f in FLOWS}
    row['notes']=['SEC original filing accession selected; USD facts divided by 1,000,000. ProfitLoss is group net income including noncontrolling interests, not parent-only NetIncomeLoss.','Contemporaneous YTD comparative flows reconcile with previously reported originals; prior annual flows are compatible.']
    if q==4:row.update(v);annual.append(row)
    else:
        pv={f:fact(f,f'{year-1}'+period[4:],f'{year-1}-01-01',a)['val']/1e6 for f in FLOWS}
        arow=next(a for a in annual if a['ticker']=='GEV' and a['period_end']==f'{year-1}-12-31')
        row.update(fiscal_year=year,fiscal_quarter=q,ytd=v,prior_ytd=pv,prior_annual=prior(arow),ttm_compatible=True)
        assert arow['availability_date']<date
        interim.append(row)
for name in ['GEV_companyfacts.json','GEV_submissions.json','TSM_companyfacts.json','TSM_submissions.json']:
    cik='0001996810' if name.startswith('GEV') else '0001046179'
    u=f'https://data.sec.gov/api/xbrl/companyfacts/CIK{cik}.json' if 'companyfacts' in name else f'https://data.sec.gov/submissions/CIK{cik}.json'
    manifest.append(dict(file=name,url=u,sha256=hashlib.sha256((DOCS/name).read_bytes()).hexdigest()))
annual.sort(key=lambda r:(r['ticker'],r['period_end']));interim.sort(key=lambda r:(r['ticker'],r['period_end']))
assert len(annual)==9 and len(interim)==21,(len(annual),len(interim))
for r in annual+interim:
    assert r['period_end']<r['publication_date']<'2026-10-01'
    assert r['total_assets']>r['current_liabilities']>0
# Exact comparative checks where a previous original is captured.
for r in interim:
    prev=next((p for p in interim if p['ticker']==r['ticker'] and p['period_end']==str(r['fiscal_year']-1)+r['period_end'][4:]),None)
    if prev:assert r['prior_ytd']==prev['ytd'],(r['ticker'],r['period_end'],r['prior_ytd'],prev['ytd'])
for name,rows in [('research_tsm_gev_annual',annual),('research_tsm_gev_interim',interim)]:
    (AREA/(name+'.json')).write_text(json.dumps(rows,indent=2)+'\n')
save('verified_facts.json',evidence);save('source_manifest.json',manifest)
(AREA/'research_tsm_gev.json').write_text(json.dumps(dict(status='complete_source_qa_passed',annual_count=9,interim_count=21,gaps=[],sources='SEC original 6-K financial exhibits for TSM; SEC 10-Q/10-K tagged companyfacts and public registration actual combined statements for GEV.',timing='Filing dates used conservatively. Only source filings before October 1, 2026. GEV listing eligibility preserved separately.',accounting_basis='TSM uses Taiwan-IFRSs for all periods; 20-F IASB-IFRS figures differ and are not combined with these interims. See sources/tsm_gev/accounting_basis_evidence.json. GEV uses US GAAP.',qa='Annual and YTD prior-period comparisons reconcile to originals. TSM exact TWD thousands, GEV group ProfitLoss, not parent-only NI. No incompatible flow basis or accounting override identified.'),indent=2)+'\n')
print('Wrote',len(annual),'annual and',len(interim),'interim observations')
